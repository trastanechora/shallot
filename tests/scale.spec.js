import {test,expect} from '@playwright/test';
test('world ruler toggles preserve soil zero, survive zoom and hide in enlarged views',async({page})=>{
 test.setTimeout(60000);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.setViewportSize({width:1440,height:1080});
 await page.goto(process.env.ATLAS_URL||'http://127.0.0.1:5173');
 const ruler=page.getByRole('switch',{name:'Tampilkan penggaris (cm)'});
 await expect(ruler).toHaveAttribute('aria-checked','true');
 await expect(page.getByTestId('scale-note')).toContainText('Skala ilustrasi');
 await expect(page.locator('[data-ruler-origin]')).toHaveAttribute('data-ruler-origin','0.38');
 await page.getByRole('switch',{name:'Tampilkan tanah'}).click();
 await expect(page.locator('[data-ruler-origin]')).toHaveAttribute('data-ruler-origin','0.38');
 await page.waitForTimeout(400);await page.locator('.specimen-stage').screenshot({path:'screenshots/scale-no-soil.png'});
 const box=await page.locator('canvas').boundingBox();
 await page.mouse.move(box.x+box.width*.6,box.y+box.height*.4);await page.mouse.down();await page.mouse.move(box.x+box.width*.8,box.y+box.height*.5,{steps:12});await page.mouse.up();
 await expect(page.locator('[data-ruler-origin]')).toHaveAttribute('data-ruler-origin','0.38');
 await page.waitForTimeout(400);await page.locator('.specimen-stage').screenshot({path:'screenshots/scale-orbit.png'});
 await ruler.click();await expect(page.locator('[data-ruler-origin]')).toHaveCount(0);
 await ruler.click();
 await page.getByRole('button',{name:'Perbesar',exact:true}).click();
 await expect(page.locator('[data-ruler-origin]')).toHaveAttribute('data-cm-reference','30');
 await page.getByRole('button',{name:'Atur ulang tampilan',exact:true}).click();
 await page.getByRole('switch',{name:'Tampilkan tanah'}).click();
 await page.waitForTimeout(1000);await page.screenshot({path:'screenshots/scale-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Detail umbi',exact:true}).click();
 await expect(ruler).toBeDisabled();await expect(page.locator('[data-ruler-origin]')).toHaveCount(0);
 await expect(page.getByTestId('scale-note')).toContainText('Penggaris disembunyikan');
 await page.getByRole('button',{name:'Tanaman utuh',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await expect(ruler).toHaveAttribute('aria-checked','true');
 await page.waitForTimeout(1000);await page.screenshot({path:'screenshots/scale-mobile.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByRole('button',{name:'1 Penanaman'}).click();
 await page.getByRole('button',{name:'Ujung atas dipotong ±⅓',exact:true}).click();
 await expect(ruler).toBeDisabled();await expect(page.locator('[data-ruler-origin]')).toHaveCount(0);
 expect(errors).toEqual([]);
});
